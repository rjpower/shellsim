/// Whether CPython's `builtins` module binds `name`.
pub(super) fn is_cpython_builtin(name: &str) -> bool {
    BUILTIN_NAMES.binary_search(&name).is_ok()
}

/// Whether `module` names a CPython standard-library module or a submodule of one.
///
/// Only the top-level package is checked, so an unmodeled submodule of a standard package counts
/// as standard even when CPython lacks it; reporting it as unsupported fails just as loudly.
pub(super) fn is_cpython_stdlib_module(module: &str) -> bool {
    let top_level = module.split('.').next().unwrap_or(module);
    STDLIB_MODULES.binary_search(&top_level).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_sorted_for_binary_search() {
        assert!(BUILTIN_NAMES.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(STDLIB_MODULES.windows(2).all(|pair| pair[0] < pair[1]));
    }

    #[test]
    fn lookup_distinguishes_builtins() {
        assert!(is_cpython_builtin("eval"));
        assert!(is_cpython_builtin("ValueError"));
        assert!(!is_cpython_builtin("undefined_name"));
    }

    #[test]
    fn stdlib_lookup_checks_the_top_level_package() {
        assert!(is_cpython_stdlib_module("threading"));
        assert!(is_cpython_stdlib_module("xml.etree.ElementTree"));
        assert!(!is_cpython_stdlib_module("requests"));
        assert!(!is_cpython_stdlib_module("numpy"));
    }
}
